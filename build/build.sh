#!/bin/bash

set -e


#########################################
# 环境检测
#########################################

OS=$(uname -s)


if [[ "$OS" == "Linux" ]]
then
    echo "Linux/WSL 环境"


elif [[ "$OS" == MINGW* ]] || [[ "$OS" == MSYS* ]]
then
    echo "Git Bash 环境"


elif [[ "$OS" == CYGWIN* ]]
then
    echo "Cygwin 环境"


else

    echo "================================"
    echo "不支持的环境: $OS"
    echo "================================"
    echo ""
    echo "请使用以下环境运行:"
    echo "  1. Git Bash"
    echo "  2. WSL/Linux"
    echo ""

    exit 1

fi



#########################################
# Docker检测
#########################################

if ! command -v docker >/dev/null 2>&1
then

    echo "================================"
    echo "未检测到 docker"
    echo "================================"
    echo ""
    echo "请安装 Docker Desktop 或 Docker Engine"
    echo ""

    exit 1

fi



#########################################
# 镜像配置
#########################################

IMAGE="hackermmzz/judge:latest"

QT_IMAGE="hackermmzz/qt-env:latest"

QT_TAR="qt-env.tar"



#########################################
# 更新基础 judge
#########################################

echo "=============================="
echo "1. 更新基础 judge"
echo "=============================="


docker pull $IMAGE || true



#########################################
# 更新 qt-env
#########################################

echo "=============================="
echo "2. 更新 qt-env"
echo "=============================="


docker pull $QT_IMAGE



#########################################
# 导出 qt-env
#########################################

echo "=============================="
echo "3. 导出 qt-env"
echo "=============================="


rm -f $QT_TAR


docker save \
    $QT_IMAGE \
    -o $QT_TAR



#########################################
# 构建 judge
#########################################

echo "=============================="
echo "4. build judge"
echo "=============================="


docker build \
    --no-cache \
    -t $IMAGE .



#########################################
# 清理临时文件
#########################################

echo "=============================="
echo "5. 清理临时文件"
echo "=============================="


rm -f $QT_TAR


docker image prune -f



#########################################
# 推送
#########################################

echo "=============================="
echo "6. push judge"
echo "=============================="


docker push $IMAGE



echo "=============================="
echo "完成"
echo "=============================="